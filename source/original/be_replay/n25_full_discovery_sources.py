"""Admission-only PREFIX2 source epoch for full66's eleven ordinary B5 jobs.

All original helpers and worker/runtime bodies remain byte-identical. Only the
literal design allowlist in the metadata module is replaced. This is untrusted
discovery; mathematical acceptance remains a separate original full replay.
"""
from __future__ import annotations
import ast
from pathlib import Path
from . import count_task as original, n25_full_count_sources as counts

ROOT=Path(__file__).resolve().parents[1]
PLAN=ROOT/"proof/n25_full_discovery_source_plan.json"
PLAN_SHA256="c948b5a679cc95b6637115d0073a2cea547e49467734a696de725823d01e627d"
need=counts.need
sha=counts.sha
encoded=counts.encoded
parsed=counts.parsed


def derive():
    """Read and transform authenticated source bytes; execute no vendor code."""
    original.verify_vendor()
    names=["count_discovery.py","prefix2_strategy.py","prefix2_runtime.py",
           "prefix2_original/MANIFEST.json"]
    names += ["prefix2_original/"+n for n in (
        "feasible_a0.py","split_policy.py","physical_prefix_lookahead.py",
        "parent_prefix_bypass.py","discovery_hoist_alpha_stoploss2.py",
        "integer_exponential_discovery_v1.py","geometry_memo_discovery_v12.py",
        "common_bound_memo_discovery_v12.py")]
    data={n:counts.base._regular(original.VENDOR/n) for n in names}
    raw=data["prefix2_strategy.py"]
    tree=ast.parse(raw)
    assignments=[n for n in tree.body if isinstance(n,ast.Assign)
                 and any(isinstance(t,ast.Name) and t.id=="ADMITTED_DESIGNS" for t in n.targets)]
    need(len(assignments)==1,"One explicit original discovery design allowlist")
    node=assignments[0]
    # Sort the literal for path/interpreter-independent generated bytes.
    statement="ADMITTED_DESIGNS = frozenset({\n"+"".join(
        "    "+repr(counts.profile(t)["design_sha256"])+",\n" for t in counts.targets())+"})\n"
    lines=raw.decode("utf-8").splitlines(keepends=True)
    changed=("".join(lines[:node.lineno-1])+statement+"".join(lines[node.end_lineno:])).encode("utf-8")
    node.value=ast.parse(statement).body[0].value
    need(ast.dump(tree)==ast.dump(ast.parse(changed)),"Only literal discovery design admission changes")
    data["prefix2_strategy.py"]=changed
    # Accelerator compatibility is a source gate, not a claim from file names.
    metadata=ast.parse(changed)
    mapping=next(n.value for n in metadata.body if isinstance(n,ast.Assign)
        and any(isinstance(t,ast.Name) and t.id=="KERNEL_PINS" for t in n.targets))
    pins=ast.literal_eval(mapping)
    for target in counts.targets():
        files=counts.profile(target)["files"]
        need(all(n in files and files[n]["sha256"]==pin for n,pin in pins.items()),
             "Each B5 capsule has every exact accelerator-compatible kernel byte")
    return data


def plan():
    raw=counts.base._regular(PLAN,4*1024**2)
    need(sha(raw)==PLAN_SHA256,"Externally pinned admission-only discovery source plan")
    obj=parsed(raw)
    need(obj["schema"]=="N25_FULL66_PREFIX2_ADMISSION_SOURCE_PLAN_V1"
         and obj["count_source_plan_sha256"]==counts.PLAN_SHA256
         and obj["arithmetic_accepted"] is False and obj["full66_complete"] is False,
         "Explicit source-only discovery epoch")
    return obj


def verify(folder):
    folder=Path(folder)
    counts.base._no_link_ancestors(folder)
    files=plan()["files"]
    actual=set()
    for p in folder.rglob("*"):
        need(not p.is_symlink() and not (hasattr(p,"is_junction") and p.is_junction()),"No linked discovery paths")
        if p.is_file():actual.add(p.relative_to(folder).as_posix())
        else:need(p.is_dir(),"Regular discovery source directory")
    need(actual==set(files),"Complete exact discovery source closure")
    for name,row in files.items():
        raw=counts.base._regular(folder/name)
        need(len(raw)==row["bytes"] and sha(raw)==row["sha256"],"Exact discovery source: "+name)
    return files


def prepare(destination):
    data=derive()
    need(counts.base._file_rows(data)==plan()["files"],"Exact fixed admission epoch derivation")
    destination=Path(destination).absolute()
    counts.base._no_link_ancestors(destination)
    need(not destination.exists(),"New discovery source epoch, no overwrite")
    destination.mkdir(parents=True,exist_ok=False)
    for name,raw in data.items():
        path=destination/name;path.parent.mkdir(exist_ok=True)
        with path.open("xb") as stream:stream.write(raw)
    verify(destination)
    return destination


def binding(folder):
    files=verify(folder)
    return dict(discovery_strategy="RESTORED_PREFIX2_V1",alpha_priority="16",traversal="depth",
        search_sha256=files["count_discovery.py"]["sha256"],
        discovery_sources_sha256={n:r["sha256"] for n,r in files.items() if n!="count_discovery.py"})
